"""
ASan Dynamic Verifier
======================
Compiles a C/C++ source file with AddressSanitizer and runs it with the
inputs generated by the LLM.  Parses the output to classify the result:

  TP          – program crashed with an ASan / signal error
  UNCONFIRMED – program exited normally (possible false positive)
  ERROR       – compilation or runner error (not a bug verdict)
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Dict, List, Optional

from config import config
from pipeline.infer_parser import BugReport
from pipeline.llm_generator import LLMResult
from utils.logger import get_logger

log = get_logger(__name__)


# ── Verdict ───────────────────────────────────────────────────────────────────

class Verdict(str, Enum):
    TRUE_POSITIVE  = "TP"          # ASan crash confirmed
    UNCONFIRMED    = "UNCONFIRMED" # ran but did not crash
    COMPILE_ERROR  = "COMPILE_ERROR"
    RUNTIME_ERROR  = "RUNTIME_ERROR"   # non-ASan crash (e.g. Python exception)
    TIMEOUT        = "TIMEOUT"
    SKIPPED        = "SKIPPED"         # not verifiable by ASan


@dataclass
class ASanResult:
    verdict:       Verdict
    crash_type:    str  = ""       # e.g. "heap-use-after-free"
    crash_line:    str  = ""       # file:line from ASan stack trace
    asan_output:   str  = ""
    stderr:        str  = ""
    returncode:    int  = 0
    compile_cmd:   str  = ""
    run_cmd:       str  = ""

    def to_dict(self) -> dict:
        return {
            "verdict":     self.verdict.value,
            "crash_type":  self.crash_type,
            "crash_line":  self.crash_line,
            "asan_output": self.asan_output[:2000],   # truncate for report
            "returncode":  self.returncode,
            "compile_cmd": self.compile_cmd,
            "run_cmd":     self.run_cmd,
        }


# ── ASan output patterns ──────────────────────────────────────────────────────

_ASAN_ERROR_RE = re.compile(
    r"ERROR: AddressSanitizer:\s*(.+?)(?:\n|$)", re.IGNORECASE
)
_UBSAN_ERROR_RE = re.compile(
    r"runtime error:\s*(.+?)(?:\n|$)", re.IGNORECASE
)
_CRASH_LOC_RE  = re.compile(
    r"#\d+\s+0x[0-9a-f]+ in \S+ (.+:\d+)", re.IGNORECASE
)
_SIGNAL_RE     = re.compile(r"signal \d+ \(SIG\w+\)", re.IGNORECASE)


# ── Verifier ─────────────────────────────────────────────────────────────────

class ASanVerifier:
    """
    Usage
    -----
    verifier = ASanVerifier()
    asan_res  = verifier.verify(report, llm_result)
    """

    def __init__(self) -> None:
        self._compiler = (
            shutil.which(config.compiler)
            or shutil.which("clang")
            or shutil.which("gcc")
            or "clang"
        )
        log.debug("Using compiler: %s", self._compiler)

    # ── Public API ────────────────────────────────────────────────────────────

    def verify(
        self,
        report: BugReport,
        llm_result: LLMResult,
    ) -> ASanResult:
        """
        Full pipeline: write helper files → compile → run → parse → classify.
        """
        if not report.is_asan_verifiable and not report.needs_instrumentation:
            log.info("[%s] Skipping: not ASan-verifiable", report.id)
            return ASanResult(Verdict.SKIPPED)

        source_path = report.resolved_path
        if source_path is None:
            log.error("[%s] No resolved source path; cannot compile.", report.id)
            return ASanResult(Verdict.COMPILE_ERROR, stderr="Source file missing")

        with tempfile.TemporaryDirectory(prefix="sv_asan_") as tmpdir:
            tmp = Path(tmpdir)
            return self._run_in_tmpdir(report, llm_result, source_path, tmp)

    # ── Internal flow ─────────────────────────────────────────────────────────

    def _run_in_tmpdir(
        self,
        report: BugReport,
        llm: LLMResult,
        source: Path,
        tmp: Path,
    ) -> ASanResult:

        # 1. Optionally inject assertion instrumentation
        src_file = self._prepare_source(report, llm, source, tmp)

        # 2. Write any file inputs the LLM requested
        self._write_file_inputs(llm, tmp)

        # 3. Compile
        binary = tmp / "target"
        compile_result = self._compile(src_file, binary)
        if compile_result is not None:
            return compile_result

        compile_cmd = self._make_compile_cmd(src_file, binary)

        # 4. Run
        return self._run(report, llm, binary, tmp, compile_cmd)

    # ── Source preparation ────────────────────────────────────────────────────

    def _prepare_source(
        self,
        report: BugReport,
        llm: LLMResult,
        source: Path,
        tmp: Path,
    ) -> Path:
        src_content = source.read_text(errors="replace")

        if llm.needs_instrumentation and llm.instrumentation_code:
            src_content = self._inject_assertion(
                src_content, report.line, llm.instrumentation_code
            )
            log.debug("[%s] Injected assertion: %s", report.id, llm.instrumentation_code)

        dst = tmp / source.name
        dst.write_text(src_content)
        return dst

    @staticmethod
    def _inject_assertion(source: str, bug_line: int, assertion: str) -> str:
        """Insert an assertion statement just before the bug line."""
        lines = source.splitlines(keepends=True)
        idx   = bug_line - 1
        if 0 <= idx < len(lines):
            indent = len(lines[idx]) - len(lines[idx].lstrip())
            lines.insert(idx, " " * indent + assertion.rstrip(";") + ";\n")
        return "".join(lines)

    # ── File inputs ───────────────────────────────────────────────────────────

    @staticmethod
    def _write_file_inputs(llm: LLMResult, tmp: Path) -> None:
        for fname, content in (llm.file_inputs or {}).items():
            dest = tmp / fname
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content)
            log.debug("Wrote file input: %s", dest)

    # ── Compilation ───────────────────────────────────────────────────────────

    def _make_compile_cmd(self, src: Path, out: Path) -> str:
        flags = config.asan_flags
        return f"{self._compiler} {flags} -o {out} {src}"

    def _compile(self, src: Path, out: Path) -> Optional[ASanResult]:
        """Returns None on success, ASanResult(COMPILE_ERROR) on failure."""
        cmd = self._make_compile_cmd(src, out)
        log.debug("Compile: %s", cmd)
        try:
            proc = subprocess.run(
                cmd,
                shell=True,
                capture_output=True,
                text=True,
                timeout=30,
            )
            if proc.returncode != 0:
                log.warning("Compilation failed:\n%s", proc.stderr[:500])
                return ASanResult(
                    Verdict.COMPILE_ERROR,
                    stderr=proc.stderr,
                    returncode=proc.returncode,
                    compile_cmd=cmd,
                )
        except subprocess.TimeoutExpired:
            return ASanResult(Verdict.COMPILE_ERROR, stderr="Compilation timed out")
        return None

    # ── Execution ─────────────────────────────────────────────────────────────

    def _run(
        self,
        report: BugReport,
        llm: LLMResult,
        binary: Path,
        cwd: Path,
        compile_cmd: str,
    ) -> ASanResult:
        cmd_parts, stdin_data = self._build_run_command(binary, llm, cwd)
        run_cmd = " ".join(cmd_parts)
        log.debug("[%s] Run: %s", report.id, run_cmd)

        import platform as _platform
        if _platform.system() == "Darwin":
            # macOS: leak detection requires SIP disabled; disable it to avoid false errors
            _asan_opts = "detect_leaks=0:print_stacktrace=1"
        else:
            _asan_opts = "detect_leaks=1:abort_on_error=0:halt_on_error=0"
        env = {**os.environ, "ASAN_OPTIONS": _asan_opts, "UBSAN_OPTIONS": "print_stacktrace=1"}
        env.update(llm.env_vars or {})

        try:
            proc = subprocess.run(
                cmd_parts,
                input=stdin_data,
                capture_output=True,
                text=True,
                timeout=config.timeout_seconds,
                cwd=str(cwd),
                env=env,
            )
        except subprocess.TimeoutExpired:
            log.warning("[%s] Execution timed out.", report.id)
            return ASanResult(
                Verdict.TIMEOUT,
                compile_cmd=compile_cmd,
                run_cmd=run_cmd,
            )
        except Exception as exc:
            return ASanResult(
                Verdict.RUNTIME_ERROR,
                stderr=str(exc),
                compile_cmd=compile_cmd,
                run_cmd=run_cmd,
            )

        combined = proc.stderr + proc.stdout
        return self._classify(combined, proc.returncode, compile_cmd, run_cmd)

    @staticmethod
    def _build_run_command(
        binary: Path,
        llm: LLMResult,
        cwd: Path,
    ) -> tuple[list[str], str]:
        """Return (cmd_list, stdin_str)."""
        cmd = [str(binary)]

        if llm.input_type == "args":
            cmd.extend(llm.args or [])
        elif llm.input_type == "file":
            # substitute $TMPDIR placeholder in args
            resolved_args = [
                str(cwd / a) if not a.startswith("-") and "." in a else a
                for a in (llm.args or [])
            ]
            cmd.extend(resolved_args)

        stdin_data = llm.stdin_data if llm.input_type in ("stdin", "args") else ""
        return cmd, stdin_data

    # ── Classification ────────────────────────────────────────────────────────

    @staticmethod
    def _classify(
        output: str,
        returncode: int,
        compile_cmd: str,
        run_cmd: str,
    ) -> ASanResult:
        crash_type = ""
        crash_line = ""

        # Check for ASan errors
        asan_match = _ASAN_ERROR_RE.search(output)
        if asan_match:
            crash_type = asan_match.group(1).strip()

        # Check for UBSan errors
        if not crash_type:
            ub_match = _UBSAN_ERROR_RE.search(output)
            if ub_match:
                crash_type = "ubsan:" + ub_match.group(1).strip()

        # Crash location
        loc_match = _CRASH_LOC_RE.search(output)
        if loc_match:
            crash_line = loc_match.group(1).strip()

        # Signal crash (Linux: negative returncode; macOS: returncode == 1 or 134)
        if not crash_type and returncode < 0:
            crash_type = f"signal:{abs(returncode)}"

        # macOS ASan exits with returncode=1 on crash (not negative like Linux)
        # Any non-zero exit from an ASan-instrumented binary means a bug was triggered
        verdict = (
            Verdict.TRUE_POSITIVE
            if (crash_type or returncode != 0)
            else Verdict.UNCONFIRMED
        )

        return ASanResult(
            verdict      = verdict,
            crash_type   = crash_type,
            crash_line   = crash_line,
            asan_output  = output,
            returncode   = returncode,
            compile_cmd  = compile_cmd,
            run_cmd      = run_cmd,
        )
